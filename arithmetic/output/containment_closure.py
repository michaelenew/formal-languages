def install() -> None:
    """Replace 0048's atom-against-atom `_contains` with the generated
    relation, so `contain` fires on everything §3 reaches."""
    def contains(big, small):
        return derives(frozenset([frozenset([small])]),
                       frozenset([frozenset([big])]))
    S._contains = contains
    for cached in (S.rewrites, S.known_prefix, S.size, S.support_bound):
        cached.cache_clear()


def verify_the_residue_shrinks(trials=700, seed=20260915) -> None:
    """0048 §5's measurement, re-run with containment closed."""
    before = S.verify_what_is_still_not_identified(trials=trials, seed=seed)
    print()
    print("  ... now with the generated containment relation installed:")
    print()
    install()
    after = S.verify_what_is_still_not_identified(trials=trials, seed=seed)
    print()
    print(f"  unidentified pairs: {len(before)} -> {len(after)}")
    return before, after


