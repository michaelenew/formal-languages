def verify_which_operators_are_monotone(trials=400, seed=20260922) -> None:
    """`A ⊑ B  ⟹  f(A) ⊑ f(B)`, tested on nested pairs."""
    generator = random.Random(seed)
    verdict = {}
    for kind in S.UNARY:
        broken = 0
        for _ in range(trials):
            base = S.random_poly(generator, 2)
            small = conj(base, S.random_poly(generator, 2))
            if not equal(conj(small, base), small):
                continue
            if not equal(conj(atom(kind, small), atom(kind, base)),
                         atom(kind, small)):
                broken += 1
        verdict[kind] = broken
    for kind, broken in verdict.items():
        mark = "monotone" if not broken else f"NOT monotone ({broken})"
        print(f"    {kind:<10} {mark}")
    assert all(verdict[kind] == 0 for kind in MONOTONE)
    assert verdict["!"] > 0
    print()
    print("  `!` is not monotone, and neither are the two measures. That is")
    print("  the third appearance of the same split (0045's Post argument,")
    print("  0048 §4's group/lattice split): `^` is the group operation and")
    print("  order does not survive it.")
    print("  Containment nonetheless CROSSES `!` -- see §3 -- because a")
    print("  down-set is closed under `^` even though `^` is not monotone.")


def verify_the_down_set_is_a_subalgebra(trials=600, seed=20260922) -> None:
    """`↓S` closed under `^`, `&`, `|` -- the step that lets containment
    cross a non-monotone operator."""
    generator = random.Random(seed)
    checked, broken = 0, []
    for _ in range(trials):
        top = S.random_poly(generator, 2)
        left = conj(S.random_poly(generator, 2), top)
        right = conj(S.random_poly(generator, 2), top)
        for label, combined in (("^", xor(left, right)),
                                ("&", conj(left, right)),
                                ("|", S.disj(left, right))):
            try:
                if not equal(conj(combined, top), combined):
                    broken.append((label, render(top)))
                checked += 1
            except RuntimeError:
                pass
    print(f"  {checked} closure checks over random down-sets")
    print(f"  {len(broken)} escape")
    for label, top in broken[:4]:
        print(f"    ESCAPES via {label}: ↓{top}")
    assert not broken
    print()
    print("  A down-set is a sublattice AND a subgroup. `A ⊑ S` and")
    print("  `B ⊑ S` give `A ^ B ⊑ S` because both sides are inside S and")
    print("  symmetric difference cannot leave. This is what makes the")
    print("  infinite-series argument work for `!`.")


