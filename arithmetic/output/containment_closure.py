"""Containment, closed the way the series were closed.

0048 drove the residue of the sentence form down to containment and
stopped there, calling it a wall. That was premature, and it repeated a
mistake this workstream already got past once: when the base algebra
could not reach carry propagation, the answer was not "the algebra is
too weak" but *write the infinite series and name its closed form* --
which is where `T`, `U`, `!` and `N` came from (0042 §1).

Containment gets the same treatment here.

**The infinite expression.** 0042 §2's first universal law is the
fixpoint,

    S(t)  =  t  ∘  σ(S t)

which unfolds to the partial sums

    T(t) = t & bt & … & b^{k-1}t & b^k(T t)
    U(t) = t | at | … | a^{k-1}t | a^k(U t)

and every unfolding is a containment statement about the closed form:
`T(t) ⊑ b^k(T t)` and `a^k(U t) ⊑ U(t)`, at every k. That is the
`1/2 + 1/4 + …` step -- the partial sums are the finite unfoldings and
the series is the closed form.

**The name.** What the unfoldings converge to is not a new operator but
a new object: the DOWN-SET

    ↓S  =  { A : A ⊑ S }

which is closed under all three joins -- `^` included, because a
down-set is a subgroup as well as a sublattice. That closure is what
lets containment cross `^`, which is not monotone. So

    U(t)  is the top of the subalgebra generated by the orbit {a^k(t)}

and `!(t) ⊑ U(t)` follows from the infinite series, not from any
monotonicity: every partial sum `⊕_{k<n} a^k(t)` lies in `↓U(t)`, and
`↓U(t)` is `^`-closed, so the limit does too.

**The closure.** §4 measures whether the relation so generated *is*
containment. It is not, and the shortfall has one shape -- §5.

Run directly for the verification suite.
"""

from __future__ import annotations

