def _peel(poly, shift):
    return S._peel_shift(poly, shift)


def _syntactically_zero(poly) -> bool:
    """`poly = 0`, decided by the prefix analysis alone.

    A polynomial confined to a window and known 0 across it is 0. This
    is what makes `a(x) & 1 = 0` available to the disjointness test
    below -- ANF stores that product as the live monomial `a(x)·1`.
    """
    bound = S.support_bound(poly)
    if bound is None:
        return not poly
    return set(S.known_prefix(poly, max(bound, 1))) == {0}


def _prefix_containment(small, big) -> bool:
    """`small ⊑ big` on a known finite window.

    When `small` is confined to `{0..k-1}` and both prefixes are known
    there, containment is a pointwise check and needs no order theory at
    all.
    """
    bound = S.support_bound(small)
    if bound is None or bound == 0:
        return bound == 0
    low, high = S.known_prefix(small, bound), S.known_prefix(big, bound)
    return all(bit == 0 or top == 1 for bit, top in zip(low, high))


def _orbit_member(element, argument, fuel):
    """Is this atom inside the subalgebra generated by `{a^k(argument)}`?

    The infinite series, made finite: `a` peels one step, and any series
    of the schema over the same argument is the closed form of a sum of
    orbit members, hence still inside.
    """
    kind, *rest = element
    if kind in ("x", "one"):
        return frozenset([frozenset([element])]) == argument
    if kind == "a":
        return _in_orbit_span(rest[0], argument, fuel)
    if kind in ORBIT_SERIES:
        return rest[0] == argument
    return False


def _in_orbit_span(poly, argument, fuel):
    if poly == argument or not poly:
        return True
    if fuel <= 0:
        return False
    return all(any(_orbit_member(element, argument, fuel - 1)
                   for element in atoms) if atoms else False
               for atoms in poly)


@functools.lru_cache(maxsize=None)
def derives(small, big, fuel: int = 4) -> bool:
    """`small ⊑ big`, from the generators of the module docstring.

    Sound by construction and checked in §3. Every clause is one of:
    a lattice law, a fixpoint unfolding, monotonicity, or the down-set
    being `^`-closed.
    """
    if not small or big == OMEGA or small == big:
        return True
    if not big or fuel <= 0:
        return False
    # down-set is ^-closed: split the sum
    if len(small) > 1:
        return all(derives(frozenset([atoms]), big, fuel - 1)
                   for atoms in small)
    (atoms,) = small
    if not atoms:                                   # small is Ω
        return big == OMEGA
    # a meet is under each of its factors
    if len(atoms) > 1:
        return any(derives(frozenset([frozenset([element])]), big, fuel - 1)
                   for element in atoms)
    (element,) = atoms
    return _atom_derives(element, big, fuel)


def _atom_derives(element, big, fuel) -> bool:
    kind, *rest = element
    argument = rest[0] if kind not in ("x", "one") else None

    # -- a known finite window: pointwise, no order theory needed ------
    if _prefix_containment(frozenset([frozenset([element])]), big):
        return True

    # -- big is U(t): the orbit argument, and the ^-closed down-set ----
    top = S._sole_atom(big)
    if top is not None and top[0] == "U":
        if _orbit_member(element, top[1], fuel):
            return True
    # -- big is N(t): anything that dies with t is under it ------------
    if top is not None and top[0] == "N":
        if S._atom_vanishes(element, top[1]) or element == top:
            return True
    # -- fixpoint, downward: T(t) ⊑ t and T(t) ⊑ sigma^k(T t) ----------
    if kind in DOWN_SERIES and derives(argument, big, fuel - 1):
        return True
    if kind in S.SERIES and S.SERIES[kind][0] == "&":
        shift = S.SERIES[kind][1]
        tail = big
        for _ in range(fuel):
            tail = _peel(tail, shift)
            if tail is None:
                break
            if tail == frozenset([frozenset([element])]):
                return True
    # -- fixpoint, upward: sigma^k(U t) ⊑ U(t) is the orbit clause -----
    # -- monotonicity --------------------------------------------------
    if kind in MONOTONE and top is not None and top[0] == kind:
        if derives(argument, top[1], fuel - 1):
            return True
    # -- lowzero(t) ⊑ t ^ Ω, the dual of lowset(t) ⊑ t ------------------
    if kind == "lowzero" and derives(xor(argument, OMEGA), big, fuel - 1):
        return True
    # -- big is a complement: A ⊑ ¬C  iff  A & C = 0 -------------------
    #
    # `Ω` is the empty monomial, so a polynomial containing it is
    # `Ω ^ C` -- the complement of the rest. Containment against a
    # complement is a disjointness question, which the prefix analysis
    # answers without any order theory.
    if frozenset() in big:
        complement = xor(big, OMEGA)
        if _syntactically_zero(conj(frozenset([frozenset([element])]),
                                    complement)):
            return True

    # -- big is a JOIN that ANF has expanded out of sight ---------------
    #
    # `P | Q` is stored as `P ^ Q ^ PQ`, so every union in the language
    # arrives as a XOR-sum and the join is not visible. Recovering one
    # is a disjointness search: if a monomial is disjoint from the rest
    # of the polynomial then the two are a union, and `A ⊑ P | Q`
    # follows from `A ⊑ P` or `A ⊑ Q`.
    for monomial in big:
        part = frozenset([monomial])
        rest = xor(big, part)
        if not rest or not _syntactically_zero(conj(part, rest)):
            continue
        if derives(frozenset([frozenset([element])]), part, fuel - 1) or \
                derives(frozenset([frozenset([element])]), rest, fuel - 1):
            return True

    # -- big is a meet: be under every factor --------------------------
    if len(big) == 1:
        (top_atoms,) = big
        if len(top_atoms) > 1:
            return all(derives(frozenset([frozenset([element])]),
                               frozenset([frozenset([factor])]), fuel - 1)
                       for factor in top_atoms)
    return False


