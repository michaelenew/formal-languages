# 3. is it sound, and what does it reach?
# ---------------------------------------------------------------------

def verify_the_relation_is_sound(trials=1500, seed=20260922) -> None:
    generator = random.Random(seed)
    claimed, wrong = 0, []
    for _ in range(trials):
        small = S.random_poly(generator, 3)
        big = S.random_poly(generator, 3)
        if not derives(small, big):
            continue
        claimed += 1
        try:
            if not equal(conj(small, big), small):
                wrong.append((render(small), render(big)))
        except RuntimeError:
            claimed -= 1
    print(f"  {claimed} derived containments, checked against the oracle")
    for small, big in wrong[:5]:
        print(f"    UNSOUND {small} ⊑ {big}")
    print(f"  {len(wrong)} are false")
    assert not wrong


def verify_the_generators_reach_the_named_cases() -> None:
    """The containments 0048 needed, and where each comes from."""
    t = X
    cases = [
        ("T(t) ⊑ t", atom("T", t), t, "fixpoint, one unfolding"),
        ("T(t) ⊑ b(T t)", atom("T", t), shift_b(atom("T", t)),
         "fixpoint, the tail"),
        ("t ⊑ U(t)", t, atom("U", t), "fixpoint, one unfolding"),
        ("a(U t) ⊑ U(t)", shift_a(atom("U", t)), atom("U", t),
         "fixpoint, the tail"),
        ("!(t) ⊑ U(t)", atom("!", t), atom("U", t),
         "the infinite series: every partial sum is in ↓U(t), which is "
         "^-closed"),
        ("a(!t) ⊑ U(t)", shift_a(atom("!", t)), atom("U", t),
         "same, one orbit step up"),
        ("a(T t) ⊑ U(t)", shift_a(atom("T", t)), atom("U", t), "same"),
        ("lowset(t) ⊑ t", atom("lowset", t), t, "measure under its series"),
        ("lowzero(t) ⊑ t ^ Ω", atom("lowzero", t), xor(t, OMEGA),
         "the dual measure"),
        ("t ⊑ N(t)", t, atom("N", t), "N is the top of anything it guards"),
        ("T(t) ⊑ U(t)", atom("T", t), atom("U", t), "orbit"),
    ]
    missed = 0
    for label, small, big, why in cases:
        true = equal(conj(small, big), small)
        got = derives(small, big)
        assert true, label
        missed += not got
        print(f"    {label:<20} {'derived' if got else 'NOT DERIVED':<12} "
              f"{why}")
    print()
    print(f"  {len(cases) - missed} of {len(cases)} reached from the")
    print("  generators. No new primitive was introduced -- the fixpoint")
    print("  law was already 0042 §2's first universal law, and 0048")
    print("  simply never implemented it.")
    return missed


