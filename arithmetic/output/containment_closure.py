def verify_the_rule_shape_is_the_limit() -> None:
    """The relation reaches `T(t) ⊑ b(T t)`; the RULE still cannot use it.

    `contain` has one shape -- drop a factor from a monomial -- and that
    shape needs `A ⊑ B` between two ATOMS sitting in the same product.
    The containment that matters here is against `b(T t)`, which is the
    polynomial `a(T t) ^ 1`. ANF has already distributed the product
    across monomials, so there is no single place to apply the law.
    """
    t = X
    small = atom("T", t)
    print(f"    T(t) ⊑ b(T t)   derived: {derives(small, shift_b(small))}"
          f"   true: {equal(conj(small, shift_b(small)), small)}")
    print(f"    T(t) ⊑ a(T t)   derived: {derives(small, shift_a(small))}"
          f"   true: {equal(conj(small, shift_a(small)), small)}")
    print()
    print("  So the factor-drop `T(t) & a(T t) -> T(t)` is FALSE, and the")
    print("  true law is the polynomial identity")
    print()
    print("      T(t) & b(T t)  =  T(t)     i.e."
          "   T(t)·a(T t)  =  T(t) ^ t&1")
    left = conj(small, shift_b(small))
    print(f"      checked: {equal(left, small)}")
    print()
    print("  which relates a two-monomial polynomial to another")
    print("  two-monomial polynomial. Nothing in the ANF term is a")
    print("  `product of A and B` any more -- the product was expanded on")
    print("  construction, the same way `|` was. Recovering it is the")
    print("  multiplicative twin of §5's hidden-join search.")
    print()
    print("  **That is where the wall actually is.** Not in containment,")
    print("  which §3-§5 close to 84%; not in the operators, which the")
    print("  fixpoint law already governs. It is that ANF is a normal form")
    print("  for ONE of the three joins, and the other two survive in it")
    print("  only as expansions a rule has to search for.")
