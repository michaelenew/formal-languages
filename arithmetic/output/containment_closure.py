MONOTONE = ("a", "U", "T", "N")          # `!`, lowset, lowzero are not
DOWN_SERIES = ("T", "lowset")            # S(t) ⊑ t
ORBIT_SERIES = ("!", "U", "T", "lowset")  # all live under U of the orbit


