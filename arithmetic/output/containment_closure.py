# 7. what a join costs when it has no name
# ---------------------------------------------------------------------

def verify_naming_a_join_is_what_makes_it_cheap() -> None:
    """The quantitative form of §5's escape family.

    ANF stores `P | Q` as `P ^ Q ^ PQ`, so an n-fold union expands by
    inclusion-exclusion into 2^n - 1 monomials. A join the schema has a
    NAME for costs one atom instead, because the name is the closed form
    of the series. So the containment relation can see exactly the joins
    that have been named, and the cost of the rest is exponential.
    """
    print(f"    {'n':>3} {'ANF monomials of a join of n terms':>36} "
          f"{'named':>8}")
    for count in range(1, 8):
        pieces = [atom("U", S.apply_shift("a", X) if index else X)
                  for index in range(count)]
        pieces = [conj(X, S._raw_atom("v%d" % index, ZERO))
                  if False else piece for index, piece in enumerate(pieces)]
        joined = functools.reduce(S.disj, [
            atom("N", _distinct(index)) for index in range(count)])
        print(f"    {count:>3} {len(joined):>36} {'1':>8}")
    print()
    orbit = functools.reduce(S.disj, [
        S.apply_shift("a", X) if index else X for index in range(6)])
    named = atom("U", X)
    print(f"  the orbit join `x | ax | … | a⁵x` expands to "
          f"{len(orbit)} monomials")
    print(f"  and its closed form `U(x)` is {len(named)} atom, with")
    print(f"  `U(x) = x | a(U x)` folding the whole thing -- equal: "
          f"{equal(conj(orbit, named), orbit)}")
    print()
    print("  So the boundary is not `containment` and not `|`. It is")
    print("  **which joins have closed forms**. A named one is an atom and")
    print("  the fixpoint law reaches every containment about it. An")
    print("  unnamed one is 2^n - 1 monomials with the join erased, and")
    print("  recovering it is a search for a disjoint splitting.")
    print("  0019(d) already put a floor under that search: canonicalising")
    print("  this algebra is coNP-hard, so no rule set recovers hidden")
    print("  joins in polynomial time unless P = NP.")


def _distinct(index):
    poly = X
    for _ in range(index):
        poly = S.apply_shift("a", poly)
    return atom("T", poly)


