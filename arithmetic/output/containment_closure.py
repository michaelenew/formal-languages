def search_for_the_boundary(trials=2500, seed=20260922, show=10):
    """True containments the generators do not reach.

    This is the measurement the whole module is for. If the generated
    relation were all of `⊑` the sentence form would be closed under
    containment and there would be no wall. It is not, and what escapes
    has a shape.
    """
    generator = random.Random(seed)
    true, derived, escaped = 0, 0, []
    for _ in range(trials):
        small = S.random_poly(generator, 3)
        big = S.random_poly(generator, 3)
        try:
            if not equal(conj(small, big), small):
                continue
        except RuntimeError:
            continue
        true += 1
        if derives(small, big):
            derived += 1
        else:
            escaped.append((small, big))
    print(f"  {true} true containments found among {trials} random pairs")
    print(f"  {derived} derived, {len(escaped)} escape "
          f"({100 * derived / max(true, 1):.0f}% reached)")
    print()
    for small, big in sorted(escaped, key=lambda pr: S.size(pr[0])
                             + S.size(pr[1]))[:show]:
        print(f"    {render(small)}   ⊑   {render(big)}")
    return escaped


def classify_the_escapes(escaped) -> None:
    """Why each escape escapes.

    Three buckets, and only one of them is about containment at all.
    """
    accidental, guarded, structural = [], [], []
    for small, big in escaped:
        if not S.normal_forms(small)[0] or not S.normal_forms(big)[0]:
            continue
        small_normal = next(iter(S.normal_forms(small)[0]))
        big_normal = next(iter(S.normal_forms(big)[0]))
        if derives(small_normal, big_normal):
            accidental.append((small, big))
        elif any(element[0] == "N"
                 for atoms in big_normal for element in atoms):
            guarded.append((small_normal, big_normal))
        else:
            structural.append((small_normal, big_normal))
    total = len(accidental) + len(guarded) + len(structural)
    print(f"  {total} escapes classified:")
    print(f"    {len(accidental):>5}  reached once both sides are normalised")
    print(f"           -- not containment gaps at all, just unreduced terms")
    print(f"    {len(guarded):>5}  the upper bound is an `N`, so the")
    print(f"           containment holds only where the guard is Ω")
    print(f"    {len(structural):>5}  genuinely outside the generators")
    for small, big in structural[:6]:
        print(f"      {render(small)}   ⊑   {render(big)}")
    return accidental, guarded, structural


