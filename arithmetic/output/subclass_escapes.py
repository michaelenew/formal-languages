def reordered_values(values: list[int], variable_count: int,
                     variable_order: list[int]) -> list[int]:
    point_count = 1 << variable_count
    rewritten = [0] * point_count
    for point in range(point_count):
        address = 0
        for position, variable in enumerate(variable_order):
            if point >> variable & 1:
                address |= 1 << (variable_count - 1 - position)
        rewritten[address] = values[point]
    return rewritten


def normalize_weights(values: tuple[int, ...]) -> tuple[int, ...]:
    """The *BMD weight normalisation: divide by the gcd, fix sign."""
    divisor = 0
    for value in values:
        divisor = math.gcd(divisor, abs(value))
    if divisor == 0:
        return values
    normalized = tuple(value // divisor for value in values)
    leading = next(value for value in normalized if value)
    if leading < 0:
        normalized = tuple(-value for value in normalized)
    return normalized


def moment_diagram_size(values: list[int], variable_count: int,
                        variable_order: list[int]) -> int:
    """Weight-normalised moment decision diagram (*BMD) size for an
    integer-valued function: children of g are g0 and g1 - g0."""
    ordered = reordered_values(values, variable_count, variable_order)
    current_level: set[tuple[int, ...]] = {
        normalize_weights(tuple(ordered))}
    total = len(current_level)
    for _ in range(variable_count):
        next_level: set[tuple[int, ...]] = set()
        for function in current_level:
            half = len(function) // 2
            low, high = function[:half], function[half:]
            next_level.add(normalize_weights(low))
            next_level.add(normalize_weights(
                tuple(b - a for a, b in zip(low, high))))
        current_level = next_level
        total += len(current_level)
    return total


def multiplication_tables(operand_width: int) -> \
        tuple[TruthTable, list[int]]:
    """(middle bit of x*y as a truth table, x*y as a word-level
    integer table); x = low bits, y = high bits."""
    operand_mask = (1 << operand_width) - 1
    middle_bit: TruthTable = []
    word_level: list[int] = []
    for point in range(1 << (2 * operand_width)):
        product = (point & operand_mask) * (point >> operand_width)
        middle_bit.append(product >> (operand_width - 1) & 1)
        word_level.append(product)
    return middle_bit, word_level


