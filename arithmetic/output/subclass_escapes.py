def gf2_eigenbasis(matrix: Matrix) -> frozenset[tuple[int, int]] | None:
    """The unique eigenbasis when the matrix has the two distinct
    GF(2) eigenvalues 0 and 1; None otherwise."""
    eigenvectors: list[tuple[int, int]] = []
    for eigenvalue in (0, 1):
        kernel = [vector for vector in ((0, 1), (1, 0), (1, 1))
                  if ((matrix[0][0] * vector[0]
                       + matrix[0][1] * vector[1]) % 2
                      == (eigenvalue * vector[0]) % 2
                      and (matrix[1][0] * vector[0]
                           + matrix[1][1] * vector[1]) % 2
                      == (eigenvalue * vector[1]) % 2)]
        if len(kernel) != 1:
            return None            # eigenvalue absent or repeated
        eigenvectors.append(kernel[0])
    return frozenset(eigenvectors)


def normalize_projective(matrix: Matrix) -> Matrix | None:
    entries = [matrix[0][0], matrix[0][1], matrix[1][0], matrix[1][1]]
    divisor = math.gcd(*(abs(entry) for entry in entries))
    if divisor == 0:
        return None
    entries = [entry // divisor for entry in entries]
    leading = next(entry for entry in entries if entry)
    if leading < 0:
        entries = [-entry for entry in entries]
    return ((entries[0], entries[1]), (entries[2], entries[3]))


def matrix_product(left: Matrix, right: Matrix) -> Matrix:
    return tuple(tuple(sum(left[row][middle] * right[middle][column]
                           for middle in range(2))
                       for column in range(2))
                 for row in range(2))          # type: ignore[return-value]


def rational_eigenbasis(matrix: Matrix) -> \
        frozenset[tuple[int, int]] | None:
    """The unique eigenbasis (as primitive integer vectors) when the
    integer matrix has two distinct rational eigenvalues."""
    trace = matrix[0][0] + matrix[1][1]
    determinant = (matrix[0][0] * matrix[1][1]
                   - matrix[0][1] * matrix[1][0])
    discriminant = trace * trace - 4 * determinant
    if discriminant <= 0:
        return None
    root = math.isqrt(discriminant)
    if root * root != discriminant or (trace + root) % 2 != 0:
        return None
    eigenvectors: list[tuple[int, int]] = []
    for doubled in (trace + root, trace - root):
        eigenvalue = doubled // 2
        row_a = (matrix[0][0] - eigenvalue, matrix[0][1])
        row_b = (matrix[1][0], matrix[1][1] - eigenvalue)
        vector = (row_a[1], -row_a[0]) if row_a != (0, 0) else \
            (row_b[1], -row_b[0])
        divisor = math.gcd(abs(vector[0]), abs(vector[1]))
        vector = (vector[0] // divisor, vector[1] // divisor)
        leading = vector[0] if vector[0] else vector[1]
        if leading < 0:
            vector = (-vector[0], -vector[1])
        eigenvectors.append(vector)
    return frozenset(eigenvectors)


