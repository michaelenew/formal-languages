def gf2_parity(masked: int) -> int:
    return bin(masked).count("1") & 1


def gf2_rank(rows: list[int]) -> int:
    basis: list[int] = []
    for row in rows:
        reduced = row
        for vector in basis:
            reduced = min(reduced, reduced ^ vector)
        if reduced:
            basis.append(reduced)
            basis.sort(reverse=True)
    return len(basis)


def gf2_invert(rows: list[int], dimension: int) -> list[int]:
    """Rows are bitmasks; returns the inverse matrix's rows."""
    augmented = [(rows[index], 1 << index)
                 for index in range(dimension)]
    for column in range(dimension):
        pivot_bit = 1 << column
        pivot_row = next(index for index in range(column, dimension)
                         if augmented[index][0] & pivot_bit)
        augmented[column], augmented[pivot_row] = \
            augmented[pivot_row], augmented[column]
        for index in range(dimension):
            if index != column and augmented[index][0] & pivot_bit:
                augmented[index] = (
                    augmented[index][0] ^ augmented[column][0],
                    augmented[index][1] ^ augmented[column][1])
    return [inverse for _, inverse in augmented]


def random_affine_system(variable_count: int, constraint_count: int,
                         source: random.Random) -> \
        tuple[list[int], list[int]]:
    while True:
        rows = [source.randrange(1, 1 << variable_count)
                for _ in range(constraint_count)]
        if gf2_rank(rows) == constraint_count:
            break
    right_sides = [source.randint(0, 1)
                   for _ in range(constraint_count)]
    return rows, right_sides


def affine_indicator_table(rows: list[int], right_sides: list[int],
                           variable_count: int) -> TruthTable:
    return [1 if all(gf2_parity(point & row) == side
                     for row, side in zip(rows, right_sides)) else 0
            for point in range(1 << variable_count)]


